"""
Experiment 17 -- Realistic drift benchmark: power of every detector at a
matched false-positive rate.

For every (dataset, encoder, N) the alarm thresholds tau_0.05 calibrated in
experiment 16 are applied to windows generated by the drift scenarios of
``src/scenarios.py`` (natural temporal drift, polarity attenuation,
annotation-boundary drift, asymmetric temporal drift, pure label shift and
label noise).  All windows consist of real review embeddings.

For each (scenario, level) we draw N_RUNS x WINDOWS_PER_RUN windows and report

* power  = fraction of windows exceeding tau_0.05 (mean and std over runs);
* AUROC  = separability between the null test windows of experiment 16 and the
           drifted windows (threshold-free);
* downstream macro-F1 of the reference-trained classifier on the window.

Outputs
    results/benchmark/bench_{key}_N{N}.csv   raw per-window statistics
    results/benchmark_summary.csv            power / AUROC per detector
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np
import pandas as pd
import torch

from experiments.common import (CONFIGS, CONTEXT_SEED, DEVICE, RESULTS_DIR, Timer, key_of, load_thresholds, log)
from src.datasets import load_dataset
from src.protocol import auroc
from src.scenarios import LEVELS, ScenarioSampler, available_scenarios
from src.statistics import ALL_DETECTORS, build_context, compute_all

BENCH_N = {('imdb', 'distilbert'): [200, 500, 1000], ('imdb', 'roberta'): [200, 500],
           ('amazon', 'distilbert'): [200], ('amazon', 'roberta'): [200]}
N_RUNS = 10
WINDOWS_PER_RUN = 10


def main(selected=None):
    (RESULTS_DIR / 'benchmark').mkdir(exist_ok=True)
    summary_path = RESULTS_DIR / 'benchmark_summary.csv'

    for name, model in CONFIGS:
        key = key_of(name, model)
        if selected and key not in selected:
            continue
        summary_rows = []
        ds = load_dataset(name, model, DEVICE)
        ctx = build_context(ds, seed=CONTEXT_SEED)
        for n in BENCH_N[(name, model)]:
            taus = load_thresholds(key, n, alpha=0.05)
            null_test = pd.read_csv(RESULTS_DIR / 'null' / f'nulltest_{key}_N{n}.csv')
            sampler = ScenarioSampler(ds, n)
            rows = []
            with Timer(f'{key} N={n} benchmark'):
                for scenario in available_scenarios(ds):
                    for lam in LEVELS[scenario]:
                        for run in range(N_RUNS):
                            rng = np.random.RandomState(20000 + 1000 * run + int(1000 * lam) + n)
                            for w in range(WINDOWS_PER_RUN):
                                e, l = sampler.draw(scenario, rng, lam)
                                r = compute_all(ctx, e, l)
                                r.update({'scenario': scenario, 'lam': lam, 'run': run, 'window': w,
                                          'pos_frac': float(l.float().mean().item())})
                                rows.append(r)
            df = pd.DataFrame(rows)
            df.to_csv(RESULTS_DIR / 'benchmark' / f'bench_{key}_N{n}.csv', index=False)

            for (scenario, lam), g in df.groupby(['scenario', 'lam']):
                for det in ALL_DETECTORS:
                    per_run = g.groupby('run')[det].apply(lambda v: float(np.mean(v.values > taus[det])))
                    summary_rows.append({
                        'key': key, 'dataset': name, 'model': model, 'N': n, 'scenario': scenario, 'lam': lam,
                        'detector': det, 'power_mean': per_run.mean(), 'power_std': per_run.std(ddof=1),
                        'auroc': auroc(null_test[det].values, g[det].values),
                        'stat_mean': g[det].mean(), 'f1_mean': g['f1'].mean(), 'f1_std': g['f1'].std(ddof=1),
                        'pos_frac_mean': g['pos_frac'].mean(), 'n_windows': len(g),
                    })
                pw = {d: np.mean(g[d].values > taus[d]) for d in ['global_mmd', 'bbsd_ks', 'cmmd', 'cond_c2st', 'error_rate']}
                log(f'  {key} N={n} {scenario:14s} lam={lam:.2f} F1={g["f1"].mean():.3f} ' +
                    ' '.join(f'{d}={v:.2f}' for d, v in pw.items()))
            pd.DataFrame(summary_rows).to_csv(RESULTS_DIR / 'benchmark' / f'summary_{key}.csv', index=False)
        del ds, ctx
        torch.cuda.empty_cache()
    # merge per-config summaries
    parts = sorted((RESULTS_DIR / 'benchmark').glob('summary_*.csv'))
    pd.concat([pd.read_csv(p) for p in parts], ignore_index=True).to_csv(summary_path, index=False)
    log('\nExperiment 17 complete.')


if __name__ == '__main__':
    main(set(sys.argv[1].split(',')) if len(sys.argv) > 1 else None)
